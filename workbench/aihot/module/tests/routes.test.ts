import {test,after} from "node:test";
import assert from "node:assert/strict";
import {mkdtempSync,writeFileSync,rmSync} from "node:fs";
import {tmpdir} from "node:os";
import path from "node:path";
import Fastify from "fastify";
import {sql,closeDb} from "@aihot/backend/db";
import {stopBoss} from "@aihot/backend/jobs/queue";
const dir=mkdtempSync(path.join(tmpdir(),"workbench-module-"));
const token="synthetic-private-service-token-for-tests";
process.env.WB_INTEL_TOKEN_FILE=path.join(dir,"token");writeFileSync(process.env.WB_INTEL_TOKEN_FILE,token);
process.env.MODEL_CALLS_ENABLED="false";
const {workbench}=await import("../server.ts");
const app=Fastify();workbench.http!(app);
after(async()=>{await app.close();await stopBoss();await closeDb();rmSync(dir,{recursive:true,force:true})});
const headers={"x-workbench-token":token};
const prefix="/internal/workbench";
test("private collector routes enforce auth, free-only config, pause and version conflicts",async()=>{
 assert.equal((await app.inject(prefix+"/snapshot")).statusCode,401);
 const bad=await app.inject({method:"POST",url:prefix+"/sources",headers,payload:{name:"Paid",feedUrl:"https://example.com/rss",kind:"x_search"}});assert.equal(bad.statusCode,400);
 const add=await app.inject({method:"POST",url:prefix+"/sources",headers,payload:{name:"Synthetic RSS",feedUrl:"https://example.com/rss"}});assert.equal(add.statusCode,201);
 const id=add.json().source.id;
 let snap=(await app.inject({url:prefix+"/snapshot",headers})).json();assert.equal(snap.modelsEnabled,false);assert.equal(snap.totals.sources,1);assert.equal(snap.totals.articles,0);assert.equal(snap.totals.paidReceipts,0);
 const source=snap.sources[0];assert.equal(source.feed_url,"https://example.com/rss");
 const pause=await app.inject({method:"PATCH",url:prefix+"/sources/"+id,headers,payload:{enabled:false,version:source.updated_at}});assert.equal(pause.statusCode,200);
 const stale=await app.inject({method:"PATCH",url:prefix+"/sources/"+id,headers,payload:{enabled:true,version:source.updated_at}});assert.equal(stale.statusCode,409);
 const fetch=await app.inject({method:"POST",url:prefix+"/sources/"+id+"/fetch",headers,payload:{}});assert.equal(fetch.statusCode,400);
 const articles=await app.inject({url:prefix+"/articles?q=hello&limit=10000",headers});assert.equal(articles.statusCode,200);assert.equal(articles.json().limit,100);
 const [count]=await sql`SELECT count(*)::int AS n FROM receipts`;assert.equal(count.n,0);
});
